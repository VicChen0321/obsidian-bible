if (!process.argv[2]) {
  throw new Error("Usage: node scripts/build-data.mjs path/to/bible_zh_cuv.json");
}
const source = path.resolve(process.argv[2]);
const output = path.resolve("src/data/cuv-data.generated.ts");

const rows = JSON.parse(fs.readFileSync(source, "utf8"));
const books = new Map(BOOK_IDS.map((id) => [id, new Map()]));

for (const row of rows) {
  const chapters = books.get(row.bookId);
  if (!chapters) throw new Error(`Unknown book id: ${row.bookId}`);
  const text = String(row.text).normalize("NFC").replace(/\s+/g, " ").trim();
  if (!text) throw new Error(`Empty text at ${row.bookId} ${row.chapter}:${row.verse}`);

  // Verses merged by the source look like "29-30": keep the text on the first verse and
  // leave the covered verses as "" (the runtime maps them back to the merged entry).
  const match = /^(\d+)(?:-(\d+))?$/.exec(String(row.verse));
  if (!match) throw new Error(`Bad verse "${row.verse}" at ${row.bookId} ${row.chapter}`);
  const start = Number(match[1]);
  const end = match[2] ? Number(match[2]) : start;
  if (end < start) throw new Error(`Bad range "${row.verse}" at ${row.bookId} ${row.chapter}`);

  const chapter = chapters.get(row.chapter) ?? new Map();
  chapters.set(row.chapter, chapter);
  for (let n = start; n <= end; n++) {
    if (chapter.has(n)) throw new Error(`Duplicate verse ${row.bookId} ${row.chapter}:${n}`);
    chapter.set(n, n === start ? text : "");
  }
}

const lines = [];
let verseSlots = 0;
for (const id of BOOK_IDS) {
  const chapters = books.get(id);
  const numbers = [...chapters.keys()].sort((a, b) => a - b);
  if (numbers.length === 0 || numbers.some((n, i) => n !== i + 1)) {
    throw new Error(`Chapters of ${id} are not contiguous from 1`);
  }
  const bookText = numbers.map((c) => {
    const chapter = chapters.get(c);
    const verses = [...chapter.keys()].sort((a, b) => a - b);
    if (verses.some((n, i) => n !== i + 1)) throw new Error(`Gap in ${id} ${c}`);
    verseSlots += verses.length;
    return verses.map((n) => chapter.get(n));
  });
  // Stored as a JSON string so the runtime only parses the book it needs.
  lines.push(`  ${JSON.stringify(id.toUpperCase())}: ${JSON.stringify(JSON.stringify(bookText))},`);
}

const header = `// AUTO-GENERATED by scripts/build-data.mjs - do not edit by hand.
// Source: bible_zh_cuv.json (see DATA_LICENSES.md for provenance).
// Each value is a JSON string of string[][] (chapter -> verse texts; "" marks a verse
// covered by the previous merged verse).
// prettier-ignore
export const CUV_BOOKS: Record<string, string> = {
`;
fs.writeFileSync(output, `${header}${lines.join("\n")}\n};\n`);
console.log(`Wrote ${path.relative(".", output)}: ${BOOK_IDS.length} books, ${verseSlots} verses`);
